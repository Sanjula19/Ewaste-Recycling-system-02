"""
services/disposition_service.py
----------------------------------
Builds a DispositionResponse for one batch of residual (non-recyclable)
waste: how much energy it carries, where it should go, and what -- if
anything -- that is worth.

WHAT THIS MODULE WILL AND WILL NOT CLAIM

  Energy content, for pyrolysis and incineration:
      E = M x LHV x eta,  reported in kWh.
  That is a property of the material and is always reported for a
  combustible batch.

  Electricity value (E x tariff) and grid CO2 avoided (E x 0.6482) are
  reported ONLY when the receiving plant both exports electricity and has
  a tariff sourced on the register. Two reasons that gate is strict:
    - A plant that exports nothing displaces no grid power, so there is
      no CO2 to avoid and no kWh to value.
    - A plant whose tariff nobody can source would have its value
      invented. Reporting nothing is the honest answer; `electricity`
      carries `reported: false` plus the reason, so a blank figure is
      never read as a zero one.
  And where it IS reported, it is labelled as the indicative value of
  electricity the PLANT generates -- not money paid to the council. A
  council handing waste to a WtE operator is not paid the feed-in tariff.

  For pyrolysis there is no electricity at all. The batch yields oil, gas
  and char (45 / 30 / 25 by mass), and this system does not know what
  those sell for, so their value is the string "not estimated" rather
  than a number nobody can defend.

CONTAMINATED GLASS IS GONE
Glass used to ride this route as an inert heat sink, charged the energy
needed to heat it to process temperature (Q = m x Cp x dT) and reported
as negative energy recovery. The material, the calculation and its
constants are all removed -- glass belongs with a glass recycler, and
materials_db.resolve_material now refuses it outright. Nothing in here
produces a negative energy figure any more.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Optional

from materials_db import (
    resolve_material,
    PYROLYSIS_EFFICIENCY,
    MJ_TO_KWH,
    GRID_EMISSION_FACTOR_KG_PER_KWH,
    PYROLYSIS_OIL_DENSITY_KG_PER_L,
)
from services import fx_service, facility_service
from services.facility_service import FacilityDistance, Origin, RouteResult
from schemas import (
    DispositionRequest,
    DispositionResponse,
    ElectricityValue,
    EnergyBreakdown,
    FacilityExclusion,
    FacilityMatch,
    FacilityRef,
    FXInfo,
    OriginRef,
    PyrolysisProducts,
)

# Stream weighting used only to split one kWh total across bio-oil /
# syngas / char for the legacy EnergyBreakdown figure the dashboard still
# reads. PyrolysisProducts below reports the real mass split instead.
_STREAM_WEIGHTS = {"oil": 1.0, "gas": 0.55, "char": 0.65}

ELECTRICITY_LABEL = (
    "indicative value of electricity generated by the plant "
    "(not paid to the council)"
)

PYROLYSIS_VALUE_NOTE = (
    "Pyrolysis yields oil, gas and char rather than electricity. This "
    "system does not hold prices for those products, so no monetary value "
    "is estimated for them."
)

_TECHNOLOGY_LABEL = {
    "pyrolysis": "Pyrolysis",
    "incineration_wte": "Waste-to-Energy",
    "mechanical_recycling": "Mechanical Recycling",
}


def _new_manifest_id() -> str:
    return f"MAN-{datetime.now(timezone.utc):%Y%m%d}-{uuid.uuid4().hex[:8].upper()}"


# ------------------------------------------------------------------ mapping

def _facility_ref(fd: FacilityDistance) -> FacilityRef:
    f = fd.facility
    return FacilityRef(
        id=f.id, name=f.name, operator=f.operator, town=f.town, district=f.district,
        technology=f.technology, status=f.status, unconfirmed=not f.is_operational,
        distance_km=fd.distance_km, latitude=f.latitude, longitude=f.longitude,
        exports_electricity=f.exports_electricity,
        tariff_lkr_per_kwh=f.tariff_lkr_per_kwh,
        source_url=f.source_url, coordinates_source=f.coordinates_source,
        last_verified=f.last_verified,
    )


def _origin_ref(origin: Origin) -> OriginRef:
    return OriginRef(name=origin.name, latitude=origin.latitude,
                     longitude=origin.longitude, source=origin.source,
                     district=origin.district)


def _exclusions(result: RouteResult) -> list[FacilityExclusion]:
    return [
        FacilityExclusion(
            id=x.facility.id, name=x.facility.name, operator=x.facility.operator,
            town=x.facility.town, technology=x.facility.technology,
            status=x.facility.status, source_url=x.facility.source_url,
            reason=x.reason,
        )
        for x in result.excluded
    ]


def _legacy_match(fd: Optional[FacilityDistance]) -> Optional[FacilityMatch]:
    """
    Fill the deprecated nearest_treatment_facility. Its latitude and
    longitude are non-optional, so a facility without coordinates can
    never appear here -- but one never reaches this point, since an
    uncoordinated facility is excluded from routing upstream.
    """
    if fd is None or not fd.facility.has_coordinates:
        return None
    f = fd.facility
    return FacilityMatch(
        name=f.name,
        facility_type=_TECHNOLOGY_LABEL.get(f.technology, f.technology),
        latitude=f.latitude, longitude=f.longitude, distance_km=fd.distance_km,
        feed_in_tariff_lkr_per_kwh=f.tariff_lkr_per_kwh,
    )


# ------------------------------------------------------------------ value

def _electricity_for(
    destination: Optional[FacilityDistance], energy_kwh: float
) -> ElectricityValue:
    """
    Electricity value and grid CO2 for one destination, or a stated
    reason for reporting neither.
    """
    if destination is None:
        return ElectricityValue(
            reported=False, label=ELECTRICITY_LABEL,
            not_reported_reason="No destination facility could be routed for this batch.",
            energy_kwh=round(energy_kwh, 2),
        )

    f = destination.facility
    if not f.exports_electricity:
        return ElectricityValue(
            reported=False, label=ELECTRICITY_LABEL, facility_name=f.name,
            energy_kwh=round(energy_kwh, 2),
            not_reported_reason=(
                f"{f.name} does not export electricity to the grid "
                f"({_TECHNOLOGY_LABEL.get(f.technology, f.technology)}), so there is "
                f"no generated electricity to value and no grid power displaced."
            ),
        )

    if f.tariff_lkr_per_kwh is None:
        return ElectricityValue(
            reported=False, label=ELECTRICITY_LABEL, facility_name=f.name,
            energy_kwh=round(energy_kwh, 2),
            not_reported_reason=(
                f"{f.name} exports electricity, but no feed-in tariff for it is "
                f"sourced on the register, so its value cannot be calculated "
                f"without inventing a rate."
            ),
        )

    return ElectricityValue(
        reported=True, label=ELECTRICITY_LABEL, facility_name=f.name,
        energy_kwh=round(energy_kwh, 2),
        tariff_lkr_per_kwh=f.tariff_lkr_per_kwh,
        value_lkr=round(energy_kwh * f.tariff_lkr_per_kwh, 2),
        grid_co2_avoided_kg=round(energy_kwh * GRID_EMISSION_FACTOR_KG_PER_KWH, 2),
    )


def _products_for(weight_kg: float, profile) -> PyrolysisProducts:
    oil_kg = weight_kg * profile.oil_frac
    gas_kg = weight_kg * profile.gas_frac
    char_kg = weight_kg * profile.char_frac
    return PyrolysisProducts(
        bio_oil_liters=round(oil_kg / PYROLYSIS_OIL_DENSITY_KG_PER_L, 2),
        bio_oil_kg=round(oil_kg, 2),
        syngas_kg=round(gas_kg, 2),
        char_kg=round(char_kg, 2),
        oil_pct=round(profile.oil_frac * 100, 1),
        gas_pct=round(profile.gas_frac * 100, 1),
        char_pct=round(profile.char_frac * 100, 1),
        value="not estimated",
        value_note=PYROLYSIS_VALUE_NOTE,
    )


def _dispatch_note(
    weight_kg: float, waste_type: str, result: RouteResult, mechanical: bool
) -> str:
    target = result.recommended or result.alternative
    if target is None:
        return (
            f"No destination could be selected for {weight_kg:g} kg of {waste_type}. "
            f"{result.recommendation_blocked_reason or ''} Hold the batch until the "
            f"facility register is completed."
        ).strip()

    f = target.facility
    caveat = (
        " This facility is marked UNCONFIRMED on the register and is offered as an "
        "alternative only -- verify it before dispatching."
        if not f.is_operational else ""
    )
    if mechanical:
        action = "for shredding, washing and granulation into recycled feedstock"
        extra = (" Do NOT route this batch to a pyrolysis or waste-to-energy plant.")
    else:
        action = (
            "for pyrolysis" if f.technology == "pyrolysis"
            else "for waste-to-energy incineration"
        )
        extra = ""
    return (
        f"Dispatch {weight_kg:g} kg of {waste_type} to {f.name} ({f.operator}), "
        f"{f.town} -- {target.distance_km} km {action}.{extra}{caveat}"
    )


# ------------------------------------------------------------------ main

def calculate_disposition(req: DispositionRequest) -> DispositionResponse:
    route, profile = resolve_material(req.waste_type)
    now_iso = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
    manifest_id = _new_manifest_id()

    if route == "recyclable_metal":
        return DispositionResponse(
            waste_type=req.waste_type,
            weight_kg=req.weight_kg,
            is_recyclable=True,
            disposition_route="Recyclable metal -- use /api/forecast for Sell/Hold valuation",
            thermal_classification=None,
            energy_recovery_kwh=0.0,
            energy_breakdown=EnergyBreakdown(
                bio_oil_liters=0.0, syngas_kwh=0.0, char_kg=0.0,
                total_kwh=0.0, yield_efficiency_pct=0.0,
            ),
            gross_energy_kwh=None,
            lhv_mj_kg=0.0,
            process_efficiency=0.0,
            landfill_diverted=True,
            co2_avoided_kg=0.0,
            manifest_id=manifest_id,
            timestamp=now_iso,
            facility_name=req.facility_name or "Urban Recycling Facility",
            nearest_treatment_facility=None,
            estimated_revenue_usd=None,
            estimated_revenue_lkr=None,
            fx=None,
        )

    fx = fx_service.get_fx_rates()
    origin = facility_service.resolve_origin(
        local_authority=req.local_authority,
        latitude=req.latitude,
        longitude=req.longitude,
    )
    result = facility_service.route_for_route_name(origin, route)
    destination = result.recommended or result.alternative

    common = dict(
        waste_type=req.waste_type,
        weight_kg=req.weight_kg,
        is_recyclable=False,
        manifest_id=manifest_id,
        timestamp=now_iso,
        facility_name=req.facility_name or "Urban Recycling Facility",
        landfill_diverted=True,
        origin=_origin_ref(origin),
        recommended_facility=_facility_ref(result.recommended) if result.recommended else None,
        alternative_facility=_facility_ref(result.alternative) if result.alternative else None,
        facilities_excluded=_exclusions(result),
        recommendation_blocked_reason=result.recommendation_blocked_reason,
        nearest_treatment_facility=_legacy_match(destination),
        estimated_revenue_usd=None,
        estimated_revenue_lkr=None,
        fx=FXInfo(**fx),
    )

    # --- Mechanical recycling (PVC): no thermal processing at all ------
    # Shredding, washing and granulating back into feedstock releases no
    # energy, so there is nothing to recover, nothing to burn and no grid
    # electricity displaced. Every energy and CO2 figure is genuinely
    # zero here rather than unmeasured.
    if profile.recycling_method == "mechanical":
        return DispositionResponse(
            disposition_route="Mechanical Recycling",
            disposition_method="mechanical",
            dispatch_note=_dispatch_note(req.weight_kg, req.waste_type, result, True),
            thermal_classification=None,
            energy_recovery_kwh=0.0,
            energy_breakdown=EnergyBreakdown(
                bio_oil_liters=0.0, syngas_kwh=0.0, char_kg=0.0,
                total_kwh=0.0, yield_efficiency_pct=0.0,
            ),
            gross_energy_kwh=None,
            lhv_mj_kg=0.0,
            process_efficiency=0.0,
            co2_avoided_kg=0.0,
            electricity=ElectricityValue(
                reported=False, label=ELECTRICITY_LABEL,
                facility_name=destination.facility.name if destination else None,
                energy_kwh=0.0,
                not_reported_reason=(
                    "Mechanical recycling involves no combustion and generates no "
                    "electricity, so there is nothing to value and no grid power "
                    "displaced."
                ),
            ),
            pyrolysis_products=None,
            **common,
        )

    # --- Combustible (polystyrene, polypropylene): E = M x LHV x eta ---
    energy_kwh = req.weight_kg * profile.lhv_mj_kg * PYROLYSIS_EFFICIENCY * MJ_TO_KWH

    oil_mass_kg = req.weight_kg * profile.oil_frac
    gas_mass_kg = req.weight_kg * profile.gas_frac
    char_mass_kg = req.weight_kg * profile.char_frac
    weighted = (
        oil_mass_kg * _STREAM_WEIGHTS["oil"]
        + gas_mass_kg * _STREAM_WEIGHTS["gas"]
        + char_mass_kg * _STREAM_WEIGHTS["char"]
    ) or 1.0
    syngas_kwh = energy_kwh * (gas_mass_kg * _STREAM_WEIGHTS["gas"]) / weighted

    electricity = _electricity_for(destination, energy_kwh)

    # Only a plant that exports on a sourced tariff displaces grid power.
    # Pyrolysis reports 0.0 with the reason carried in `electricity`.
    co2_avoided_kg = electricity.grid_co2_avoided_kg or 0.0

    going_to_incinerator = destination is not None and \
        destination.facility.technology == "incineration_wte"
    disposition_route = (
        "Waste-to-Energy Incineration" if going_to_incinerator else "Pyrolysis Processing"
    )

    return DispositionResponse(
        disposition_route=disposition_route,
        disposition_method="pyrolysis",
        dispatch_note=_dispatch_note(req.weight_kg, req.waste_type, result, False),
        thermal_classification="combustible",
        # NOT pre-rounded. These values are summed across a whole cycle in
        # the manifest, and rounding each batch to 2 dp first compounds:
        # 100 identical 7 kg PP batches drift 0.33 kWh from the true total.
        # Rounding belongs at the point of display, once.
        energy_recovery_kwh=energy_kwh,
        energy_breakdown=EnergyBreakdown(          # display-only, rounded is fine
            bio_oil_liters=round(oil_mass_kg / PYROLYSIS_OIL_DENSITY_KG_PER_L, 2),
            syngas_kwh=round(syngas_kwh, 2),
            char_kg=round(char_mass_kg, 2),
            total_kwh=round(energy_kwh, 2),
            yield_efficiency_pct=round(PYROLYSIS_EFFICIENCY * 100, 1),
        ),
        # Equal to energy_recovery_kwh now that the heat-sink deduction is
        # gone. Kept so an existing dashboard build still renders.
        gross_energy_kwh=energy_kwh,
        lhv_mj_kg=profile.lhv_mj_kg,
        process_efficiency=PYROLYSIS_EFFICIENCY,
        co2_avoided_kg=co2_avoided_kg,
        electricity=electricity,
        # The batch's own pyrolysis yield. Reported for the material's
        # recommended technology even when the only routable destination
        # is an incinerator, so an operator can see what is forgone by
        # taking the alternative.
        pyrolysis_products=_products_for(req.weight_kg, profile),
        **common,
    )
